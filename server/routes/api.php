<?php

use App\Http\Controllers\Api\V1\AdminUserProvisionController;
use App\Http\Controllers\Api\V1\AdminUserStatusController;
use App\Http\Controllers\Api\V1\AppointmentController;
use App\Http\Controllers\Api\V1\BookmarkController;
use App\Http\Controllers\Api\V1\ContentController;
use App\Http\Controllers\Api\V1\DiagnosisController;
use App\Http\Controllers\Api\V1\NotificationController;
use App\Http\Controllers\Api\V1\PatientController;
use App\Http\Controllers\Api\V1\ProfileController;
use App\Http\Controllers\Api\V1\ScheduleController;
use App\Http\Controllers\Api\V1\SlotController;
use App\Http\Controllers\Api\V1\SoapController;
use App\Http\Controllers\Api\V1\UserController;
use App\Http\Controllers\Auth\ActivationController;
use App\Http\Controllers\Auth\EmailChangeController;
use App\Http\Controllers\Auth\PasswordController;
use App\Http\Controllers\Auth\RegistrationController;
use App\Http\Controllers\Auth\SessionController;
use Illuminate\Broadcasting\BroadcastController;
use Illuminate\Support\Facades\Route;

Route::get('/diagnoses', DiagnosisController::class)->name('diagnoses.index');
Route::post('/registrations/patient', [RegistrationController::class, 'storePatient'])
    ->middleware('throttle:registration')->name('registrations.patient');
Route::post('/activation/otp/verify', [ActivationController::class, 'verify'])->middleware('throttle:activation');
Route::post('/activation/otp/resend', [ActivationController::class, 'resend'])->middleware('throttle:activation-resend');
Route::post('/activation', [ActivationController::class, 'activate'])->middleware('throttle:activation');
Route::post('/forgot-password', [PasswordController::class, 'forgot'])->middleware('throttle:3,1');
Route::post('/reset-password', [PasswordController::class, 'reset'])->middleware('throttle:5,1');

Route::middleware(['auth:sanctum', 'account.active', 'verified'])->group(function (): void {
    Route::post('/broadcasting/auth', [BroadcastController::class, 'authenticate'])->name('broadcasting.auth');
    Route::get('/me', [SessionController::class, 'show'])->name('me.show');
    Route::get('/notifications/channel', [NotificationController::class, 'channel'])->name('notifications.channel');
    Route::get('/notifications', [NotificationController::class, 'index'])->name('notifications.index');
    Route::post('/notifications', [NotificationController::class, 'store'])->name('notifications.store');
    Route::patch('/notifications/{notification}/read', [NotificationController::class, 'read'])->name('notifications.read');
    Route::patch('/me', [ProfileController::class, 'update']);
    Route::post('/me/password', [PasswordController::class, 'change']);
    Route::post('/me/email-change', [EmailChangeController::class, 'request'])->middleware('throttle:3,1');
    Route::post('/email-change/confirm', [EmailChangeController::class, 'confirm'])->middleware('throttle:10,1');
    Route::get('/users/counts', [UserController::class, 'counts']);
    Route::post('/users', AdminUserProvisionController::class);
    Route::get('/users', [UserController::class, 'index']);
    Route::patch('/users/{user}/status', AdminUserStatusController::class);
    Route::get('/users/{user}', [UserController::class, 'show']);
    Route::get('/content', [ContentController::class, 'index'])->name('content.index');
    Route::put('/content/{content}/bookmark', [BookmarkController::class, 'store'])->name('content.bookmark.store');
    Route::delete('/content/{content}/bookmark', [BookmarkController::class, 'destroy'])->name('content.bookmark.destroy');
    Route::get('/bookmarks', [ContentController::class, 'bookmarks'])->name('bookmarks.index');
    Route::post('/content', [ContentController::class, 'store'])->name('content.store');
    Route::patch('/content/{content}', [ContentController::class, 'update'])->name('content.update');
    Route::delete('/content/{content}', [ContentController::class, 'destroy'])->name('content.destroy');
    Route::get('/content/{content}', [ContentController::class, 'show'])->name('content.show');
    Route::post('/schedules', [ScheduleController::class, 'store'])->name('schedules.store');
    Route::get('/slots', [SlotController::class, 'index'])->name('slots.index');
    Route::get('/slots/{slot}', [SlotController::class, 'show'])->name('slots.show');
    Route::post('/slots/{slot}/book', [AppointmentController::class, 'store'])->name('slots.book');
    Route::get('/appointments', [AppointmentController::class, 'index'])->name('appointments.index');
    Route::get('/appointments/{appointment}', [AppointmentController::class, 'show'])->name('appointments.show');
    Route::post('/appointments/{appointment}/accept', [AppointmentController::class, 'accept'])->name('appointments.accept');
    Route::post('/appointments/{appointment}/reject', [AppointmentController::class, 'reject'])->name('appointments.reject');
    Route::post('/appointments/{appointment}/cancel', [AppointmentController::class, 'cancel'])->name('appointments.cancel');
    Route::post('/appointments/{appointment}/complete', [AppointmentController::class, 'complete'])->name('appointments.complete');
    Route::get('/patients', [PatientController::class, 'index'])->name('patients.index');
    Route::get('/soaps/patient/{patient}', [SoapController::class, 'index'])->name('soaps.patient.index');
    Route::post('/soaps/{patient}', [SoapController::class, 'store'])->name('soaps.store');
    Route::get('/soaps/{soap}', [SoapController::class, 'show'])->name('soaps.show');
    Route::patch('/soaps/{soap}', [SoapController::class, 'update'])->name('soaps.update');
});
